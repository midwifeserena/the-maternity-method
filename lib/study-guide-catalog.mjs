export function mergeStudyGuides(existing=[]){
 const guides=[...studyGuideCatalog],ids=new Set(guides.map(g=>g.id)),urls=new Set(guides.map(g=>g.file_url));
 for(const guide of existing){if(!guide||!guide.id||!guide.file_url||ids.has(guide.id)||urls.has(guide.file_url))continue;guides.push(guide);ids.add(guide.id);urls.add(guide.file_url);}
 return guides;
}

export function filterStudyGuides(guides,category='All',query=''){
 const search=query.trim().toLocaleLowerCase();
 return guides.filter(g=>(category==='All'||(g.categories??[g.category]).includes(category))&&(!search||[g.title,g.description,g.category,...(g.categories??[])].join(' ').toLocaleLowerCase().includes(search)));
}
